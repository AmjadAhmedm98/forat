export const hasImage = (a: Article) => imageQuality(a) !== "text";
export const withImage = (list = ALL) => list.filter(hasImage);
export const featured = () => ARTICLES.filter((a) => a.featured);
export const latest = (n = 8) => [...ALL].sort((a, b) => a.agoMin - b.agoMin).slice(0, n);
export const trending = (n = 6) => [...ALL].sort((a, b) => b.views - a.views).slice(0, n);

export const related = (a: Article, n = 4) =>
  ALL.filter((x) => x.slug !== a.slug && hasImage(x) &&
    (x.category === a.category || x.tags.some((t) => a.tags.includes(t)))).slice(0, n);

export const nextArticle = (a: Article) => {
  const pool = ALL.filter(hasImage);
  const i = pool.findIndex((x) => x.slug === a.slug);
  return pool[(i + 1) % pool.length];
};

/** عدد المواد في كل قسم */
export const countIn = (k: CategoryKey) => ALL.filter((a) => a.category === k).length;
